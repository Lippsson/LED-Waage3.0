import 'dart:ui' as ui;

import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// Minimal in-app localisation: German, English, Swedish.
/// `tr('key')` looks up the current language; `{name}` placeholders are replaced from [args].
const supportedLanguages = <String, String>{
  'de': 'Deutsch',
  'en': 'English',
  'sv': 'Svenska',
};

final ValueNotifier<String> appLang = ValueNotifier<String>('de');

Future<void> initLanguage() async {
  String lang;
  try {
    final prefs = await SharedPreferences.getInstance();
    lang = prefs.getString('lang') ?? ui.PlatformDispatcher.instance.locale.languageCode;
  } catch (_) {
    lang = ui.PlatformDispatcher.instance.locale.languageCode;
  }
  appLang.value = supportedLanguages.containsKey(lang) ? lang : 'de';
}

Future<void> setLanguage(String lang) async {
  if (!supportedLanguages.containsKey(lang)) return;
  appLang.value = lang;
  try {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('lang', lang);
  } catch (_) {}
}

String tr(String key, [Map<String, String>? args]) {
  var s = _strings[appLang.value]?[key] ?? _strings['en']?[key] ?? _strings['de']?[key] ?? key;
  args?.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// Maps the English reason strings sent by the firmware to translated text.
String trCalError(String reason) {
  if (reason == 'Cancelled') return tr('err_cancelled');
  if (reason.startsWith('Not horizontal')) return tr('err_not_horizontal');
  if (reason.startsWith('Not vertical')) return tr('err_not_vertical');
  if (reason.startsWith('Movement')) return tr('err_movement');
  if (reason.startsWith('Same end')) return tr('err_same_end');
  if (reason.startsWith('End changed')) return tr('err_end_changed');
  if (reason.startsWith('Connection lost')) return tr('err_conn_lost');
  if (reason.startsWith('Not in level mode')) return tr('err_not_level_mode');
  return reason;
}

